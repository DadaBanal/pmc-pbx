'use strict';
/*
 * Yealink driver. One file per phone, named after its MAC, fetched with that phone's own password.
 *
 * Measured from the vendor datasheets (T31P read 7 Oct 2026, T30P read 9 Oct 2026): auto-provision over
 * FTP/TFTP/HTTP/HTTPS, TLS 1.3, SRTP, HTTPS certificate manager, PoE 802.3af class 1.
 *
 * Key difference inside the family, measured from Yealink's own support documentation:
 *   "Line key does not apply to T30P/T30/T19 E2/T19P E2/CP920 phones"
 *   Busy Lamp Field "is not available on the T30P/T30/T19 E2/T19P E2/CP920 IP phone."
 * So the T30P takes no linekey block at all; writing one would be noise the phone ignores.
 */

const MODELS = {
  T31P: { label: 'Yealink T31P desk phone', accounts: 2, lineKeys: 2, blf: true },
  T31G: { label: 'Yealink T31G desk phone (gigabit)', accounts: 2, lineKeys: 2, blf: true },
  T33G: { label: 'Yealink T33G desk phone (colour)', accounts: 4, lineKeys: 4, blf: true },
  T30P: { label: 'Yealink T30P desk phone (no buttons)', accounts: 1, lineKeys: 0, blf: false }
};

function perPhoneFile(e, ctx) {
  const { cfg, dir, secrets } = ctx;
  const m = MODELS[e.model];
  const L = [];
  L.push('#!version:1.0.0.1');
  L.push('## GENERATED by pmc-pbx for ' + e.ext + ' ' + e.name + ' (' + e.mac + ') ' + new Date().toISOString());
  L.push('');
  L.push('static.auto_provision.server.url = ' + cfg.provUrl);
  L.push('static.auto_provision.server.username = ' + e.mac);
  L.push('static.auto_provision.server.password = ' + secrets.prov[e.mac]);
  L.push('static.auto_provision.power_on = 1');
  L.push('static.auto_provision.repeat.enable = 1');
  L.push('static.auto_provision.repeat.minutes = 1440');
  L.push('static.security.trust_certificates = 1');
  L.push('');
  L.push('account.1.enable = 1');
  L.push('account.1.label = ' + e.ext);
  L.push('account.1.display_name = ' + e.name);
  L.push('account.1.auth_name = ' + e.ext);
  L.push('account.1.user_name = ' + e.ext);
  L.push('account.1.password = ' + secrets.sip[e.ext]);
  L.push('account.1.sip_server.1.address = ' + cfg.fqdn);
  L.push('account.1.sip_server.1.port = ' + cfg.sipPort);
  L.push('account.1.sip_server.1.transport_type = 2');
  L.push('account.1.sip_server.1.expires = 300');
  L.push('account.1.srtp_encryption = 2');
  L.push('account.1.outbound_proxy_enable = 0');
  L.push('account.1.dtmf.type = 1');
  L.push('account.1.codec.1.enable = 1');
  L.push('account.1.codec.1.payload_type = G722');
  L.push('account.1.codec.1.priority = 1');
  L.push('account.1.codec.2.enable = 1');
  L.push('account.1.codec.2.payload_type = PCMA');
  L.push('account.1.codec.2.priority = 2');
  L.push('account.1.codec.3.enable = 1');
  L.push('account.1.codec.3.payload_type = PCMU');
  L.push('account.1.codec.3.priority = 3');
  L.push('account.1.subscribe_mwi = ' + (e.voicemail ? '1' : '0'));
  L.push('voice_mail.number.1 = *97');
  L.push('');
  L.push('features.remote_phonebook.enable = 1');
  L.push('remote_phonebook.data.1.url = ' + cfg.provUrl + 'phonebook.xml');
  L.push('remote_phonebook.data.1.name = PMC');
  L.push('');
  L.push('local_time.time_zone = +8');
  L.push('local_time.time_zone_name = Philippines(Manila)');
  L.push('local_time.ntp_server1 = ' + (cfg.ntpServer || 'pool.ntp.org'));
  L.push('lang.gui = English');
  L.push('');
  if (m.lineKeys > 0) {
    (e.keys || []).slice(0, m.lineKeys).forEach((k, i) => {
      const n = i + 1;
      const target = dir.extensions.find(x => x.ext === k.ext) || {};
      L.push('linekey.' + n + '.type = ' + (k.type === 'blf' ? '16' : '13'));
      L.push('linekey.' + n + '.line = 1');
      L.push('linekey.' + n + '.value = ' + k.ext);
      L.push('linekey.' + n + '.label = ' + (k.label || target.name || k.ext));
    });
  } else if ((e.keys || []).length) {
    L.push('## ' + (e.keys || []).length + ' button(s) in the directory are not written: this model has no line keys.');
  }
  L.push('');
  return { name: e.mac + '.cfg', body: L.join('\n'), type: 'text/plain' };
}

function phonebook(dir) {
  const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  const rows = dir.extensions.slice().sort((a, b) => a.name.localeCompare(b.name));
  const L = ['<?xml version="1.0" encoding="UTF-8"?>', '<YealinkIPPhoneDirectory>'];
  for (const e of rows) {
    L.push('  <DirectoryEntry><Name>' + esc(e.name) + (e.dept ? ' - ' + esc(e.dept) : '') + '</Name><Telephone>' + esc(e.ext) + '</Telephone></DirectoryEntry>');
  }
  L.push('</YealinkIPPhoneDirectory>', '');
  return { name: 'phonebook.xml', body: L.join('\n'), type: 'text/xml' };
}

module.exports = {
  id: 'yealink',
  vendor: 'Yealink',
  models: MODELS,
  auth: 'per-mac',          // each phone fetches its own file with its own password
  perPhoneFile,
  // One shared file for the whole fleet: the directory the phones show under Contacts.
  sharedFiles: (phones, ctx) => (phones.length ? [phonebook(ctx.dir)] : []),
  setupNotes: e => ([
    'Provisioning address: ' + e.url,
    'User name: ' + e.mac,
    'Password: ' + (e.provPassword || '(created at the next Apply)'),
    'The phone takes everything else from that file. Enter these once under Settings, Auto Provision, or let DHCP option 66 hand them over.'
  ])
};
