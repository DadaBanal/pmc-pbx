'use strict';
/*
 * Avaya J100 driver (Open SIP). A different shape from Yealink, and the reason this folder exists.
 *
 * MEASURED, 9 Oct 2026:
 *  - Avaya's J100 SIP 4.1.10.0 release notes name "Open SIP Platforms: ... Asterisk R16" as supported, and
 *    Avaya publishes "Installing and Administering Avaya J100 Series SIP IP Phones in Open SIP".
 *  - Every Avaya phone fetches the SAME file, 46xxsettings.txt, over HTTP or HTTPS. Per-phone differences are
 *    made inside it with IF/GOTO branches, not with one file per phone (Avaya, "Configuring the phone using
 *    the settings file": lines begin with SET, IF, GOTO, #, ADD or GET; $MACADDR is a substitution variable).
 *  - The per-phone IDENTITY is a login at the handset: SIP user ID, authentication user ID and password are
 *    entered on the phone (emetrotel, RingCentral and Intermedia all describe the same login). So this file
 *    carries NO per-phone secret, and the screen's "first-time setup details" give the engineer the extension
 *    and its password to type in once.
 *  - Avaya ships no phone with the Open SIP load; Intermedia's guide records that the Open SIP firmware is a
 *    free download. A J179 bought for an Aura or IP Office system must be flashed before any of this applies.
 *
 * Parameter names used below were read from Avaya's own material; none is invented:
 *   SIP_CONTROLLER_LIST, SIPDOMAIN, ENFORCE_SIPS_URI, MEDIAENCRYPTION, SDPCAPNEG, TRUSTCERTS, HTTPSRVR, HTTPDIR.
 * Two settings come from an independent interoperability note (traud.de) for Asterisk specifically:
 *   SDPCAPNEG 0 (its "SDP Negotiation Capability: No") and the Opus codec turned off.
 *
 * UNPROVEN until the first physical J179 (phase 3 of the design): the exact spelling of the Opus control and
 * whether the shared file can be served behind HTTP basic auth. Both are marked in the file itself.
 */

// The panel's list name; generate.js writes the list itself under the same name (a test holds the two together).
const PANEL = 'pmc-panel';

const MODELS = {
  J179: { label: 'Avaya J179 desk phone (Open SIP)', accounts: 8, lineKeys: 8, blf: true },
  J169: { label: 'Avaya J169 desk phone (Open SIP)', accounts: 8, lineKeys: 8, blf: true },
  J139: { label: 'Avaya J139 desk phone (Open SIP)', accounts: 4, lineKeys: 4, blf: true }
};

// Avaya compares $MACADDR as upper-case hex with no separators.
const macFor = e => String(e.mac || '').toUpperCase();

function settingsFile(phones, ctx) {
  const { cfg } = ctx;
  const host = cfg.fqdn;
  const L = [];
  L.push('## GENERATED by pmc-pbx ' + new Date().toISOString() + ' - do not edit, edit the directory');
  L.push('## Avaya J100 series, Open SIP. Every Avaya phone fetches this one file; the branches below set the');
  L.push('## display name per handset. The SIP user name and password are entered at the phone itself.');
  L.push('');
  L.push('## ---- the call server ----');
  L.push('SET SIP_CONTROLLER_LIST ' + host + ':' + cfg.sipPort + ';transport=tls');
  L.push('SET SIPDOMAIN ' + host);
  L.push('SET ENFORCE_SIPS_URI 1');
  L.push('');
  L.push('## ---- not an Avaya call server ----');
  L.push('## First J179, 15 Oct 2026: without these it asked for Avaya PPM (/axis/services/PPM) and sat on');
  L.push('## "Acquiring Service". Values from Cisco BroadWorks\' Avaya J100 partner configuration guide.');
  L.push('SET ENABLE_AVAYA_ENVIRONMENT 0');
  L.push('SET DISCOVER_AVAYA_ENVIRONMENT 0');
  L.push('SET ENABLE_IPOFFICE 0');
  L.push('SET ENABLE_3PCC_ENVIRONMENT 1');
  L.push('');
  L.push('## ---- media security: SRTP, and the two settings Asterisk needs ----');
  L.push('SET MEDIAENCRYPTION 1');
  L.push('SET SDPCAPNEG 0');
  L.push('## First J179, 15 Oct 2026, no audio: its crypto line carried UNENCRYPTED_SRTCP, Asterisk refused it');
  L.push('## ("Unsupported crypto parameters"), and sent the phone no RTP. ENCRYPT_SRTCP 1 drops that flag (Avaya:');
  L.push('## "Specifies whether RTCP packets are encrypted", default 0).');
  L.push('SET ENCRYPT_SRTCP 1');
  L.push('');
  L.push('## ---- the root certificate the SIP server\'s chain ends at ----');
  L.push('## First J179: every TLS connection to 5061 ended "tlsv1 alert unknown ca". TRUSTCERTS names PEM files the');
  L.push('## phone downloads from the file server and trusts. HTTPSRVR is not set: the phone keeps the HTTPS address');
  L.push('## typed at the handset, and this server answers HTTPS only.');
  L.push('SET TRUSTCERTS ' + trustCerts(cfg).map(c => c.name).join(','));
  // config avayaTlsNameCheck false: the phone stops matching the server's name to its certificate (RFC 2818); the
  // chain must still end at a root in TRUSTCERTS. First J179, 15 Oct 2026: TLS completed, then the phone sent an
  // alert and closed before any SIP. Off only to find out whether that check is what refuses us.
  if (cfg.avayaTlsNameCheck === false) L.push('SET TLSSRVRID 0');
  L.push('');
  L.push('## ---- voicemail key and message lamp ----');
  L.push('## Avaya: MSGNUM is the number the Message key dials. Cisco BroadWorks J100 guide: PSTN_VM_NUM, and');
  L.push('## SUBSCRIBE_LIST_NON_AVAYA "message-summary" for the lamp. *97 is this PBX\'s voicemail.');
  L.push('SET MSGNUM *97');
  L.push('SET PSTN_VM_NUM *97');
  L.push('SET SUBSCRIBE_LIST_NON_AVAYA "message-summary"');
  L.push('');
  L.push('## ---- quick extension panel ----');
  L.push('## The phone subscribes to this list and puts a key on screen for each extension in it, lit by its');
  L.push('## call state (Cisco BroadWorks J100 guide, Busy Lamp Field). The list is [' + PANEL + '] in pjsip_pmc.conf.');
  L.push('SET BLF_LIST_URI "sips:' + PANEL + '@' + host + '"');
  L.push('');
  L.push('## ---- time ----');
  L.push('SET SNTPSRVR ' + (cfg.ntpServer || 'pool.ntp.org'));
  L.push('SET GMTOFFSET +8:00');
  L.push('SET DSTOFFSET 0');
  L.push('');
  L.push('## ---- codecs ----');
  L.push('## The Opus codec runs fast or slow against Asterisk (independent interoperability note), so it is');
  L.push('## turned off at the phone. CONFIRM THE EXACT PARAMETER on the first handset: Avaya documents an');
  L.push('## OPUS control under "Codecs and DTMF" but its settings-file spelling was not measured.');
  L.push('## SET ENABLE_OPUS 0');
  L.push('');
  const all = backgroundAll(cfg);
  if (all) {
    L.push('## ---- background picture, every handset ----');
    L.push('SET BACKGROUND_IMAGE "' + all.name + '"');
    L.push('SET BACKGROUND_IMAGE_DISPLAY ' + all.name);
    L.push('');
  }
  if (phones.length) {
    L.push('## ---- per handset ----');
    phones.forEach((e, i) => {
      const label = 'PH' + (i + 1);
      L.push('IF $MACADDR SEQ ' + macFor(e) + ' GOTO ' + label);
    });
    L.push('GOTO END');
    L.push('');
    phones.forEach((e, i) => {
      const label = 'PH' + (i + 1);
      // "##" is a comment and "#" a GOTO target (pbxbook, IP Office set files); a bare label line is not valid
      L.push('## ' + label + ': ' + e.ext + ' ' + e.name + (e.dept ? ' (' + e.dept + ')' : ''));
      L.push('# ' + label);
      L.push('SET PHNNUMOFSA 1');
      L.push('SET PHONE_LABEL "' + String(e.name).replace(/"/g, '') + '"');
      const bg = backgroundFor(e, cfg);
      if (bg) { L.push('SET BACKGROUND_IMAGE "' + bg.name + '"'); L.push('SET BACKGROUND_IMAGE_DISPLAY ' + bg.name); }
      L.push('GOTO END');
      L.push('');
    });
    L.push('# END');
  }
  L.push('');
  return { name: '46xxsettings.txt', body: L.join('\n'), type: 'text/plain' };
}

/*
 * A handset's own background picture (Dada, 15 Oct 2026, for 6666 PMO Support: "pls add this as the wallpaper").
 * Avaya: BACKGROUND_IMAGE names the files the phone fetches, BACKGROUND_IMAGE_DISPLAY the one it shows (IP Office
 * 12.3 "J100 Phone Background Image Controls"). JPEG only, at most 256 KB, 320 x 240 on a J179 (pbxbook, tek-tips,
 * tonyfernandeztech agree). A picture that is missing, not a JPEG or too big is left out, never half-served.
 */
const MAX_BG = 256 * 1024;
function backgroundFor(e, cfg) {
  return picture((cfg.avayaBackgrounds || {})[e.mac], cfg);
}
// every Avaya handset (Dada, 15 Oct 2026: "also add the wall paper on all of it"); a per-MAC picture still wins
function backgroundAll(cfg) {
  return picture(cfg.avayaBackgroundAll, cfg);
}
function picture(name, cfg) {
  if (!name || !/^[A-Za-z0-9._-]{1,60}\.jpg$/.test(String(name))) return null;
  const file = require('path').join(cfg.phoneImagesDir || '', name);
  let body;
  try { body = require('fs').readFileSync(file); } catch (err) { return null; }
  if (body.length > MAX_BG || body[0] !== 0xff || body[1] !== 0xd8) return null;
  return { name, body, type: 'image/jpeg' };
}

// CA certificates the phones must trust, from config avayaTrustCerts ("a.pem,b.pem") in <conf>/phone-certs. Only a
// readable PEM certificate is named or served; anything else is left out.
function trustCerts(cfg) {
  const names = String(cfg.avayaTrustCerts || '').split(',').map(s => s.trim()).filter(n => /^[A-Za-z0-9._-]{1,60}\.pem$/.test(n));
  const out = [];
  for (const name of names) {
    let body;
    try { body = require('fs').readFileSync(require('path').join(cfg.phoneCertsDir || '', name), 'utf8'); } catch (err) { continue; }
    if (!/^-----BEGIN CERTIFICATE-----/.test(body.trim())) continue;
    out.push({ name, body, type: 'application/x-pem-file' });
  }
  return out;
}

function upgradeFile() {
  const L = ['## GENERATED by pmc-pbx - no firmware upgrade is offered; go straight to the settings file', 'GET 46xxsettings.txt', ''];
  return { name: 'J100Supgrade.txt', body: L.join('\n'), type: 'text/plain' };
}

module.exports = {
  id: 'avaya',
  vendor: 'Avaya',
  models: MODELS,
  // One file for every Avaya phone; it holds no per-phone secret, and the handset sends no password for it (no
  // per-phone file, so no provisioning password is ever made for an Avaya MAC). Served without a password, to the
  // networks in config provNetworks only (Dada, 15 Oct 2026: "yes to the network only").
  auth: 'lan',
  perPhoneFile: null,
  // A J100 asks for J100Supgrade.txt first and shows "Connection error" when it is missing (first J179, 15 Oct 2026:
  // five 404s on /prov/J100Supgrade.txt, no request for the settings). Avaya: "The Avaya-provided upgrade file
  // includes a line that tells the phones to GET 46xxsettings.txt". Ours carries only that line: no firmware is
  // named, so nothing is ever flashed from here.
  sharedFiles: (phones, ctx) => {
    if (!phones.length) return [];
    const pictures = new Map();
    const all = backgroundAll(ctx.cfg); if (all) pictures.set(all.name, all);
    for (const e of phones) { const bg = backgroundFor(e, ctx.cfg); if (bg) pictures.set(bg.name, bg); }
    return [upgradeFile(), settingsFile(phones, ctx), ...trustCerts(ctx.cfg), ...pictures.values()];
  },
  setupNotes: e => ([
    'Firmware: the handset must carry the Open SIP load, not an Aura or IP Office one. Flash it first.',
    'File server: ' + e.url.replace(/\/$/, '') + ' serves 46xxsettings.txt; set it under Admin, default access code 27238.',
    'At the phone, log in with SIP user ID ' + e.ext + ', authentication user ID ' + e.ext + ',',
    'password: ' + (e.sipPassword || '(created at the next Apply)'),
    'This phone takes no per-phone file; everything else comes from the shared settings file.'
  ])
};
