'use strict';
/*
 * Avaya J100 driver (Open SIP). A different shape from Yealink, and the reason this folder exists.
 *
 * MEASURED, 9 Oct 2026:
 *  - Avaya's J100 SIP 4.1.10.0 release notes name "Open SIP Platforms: ... Asterisk R16" as supported, and
 *    Avaya publishes "Installing and Administering Avaya J100 Series SIP IP Phones in Open SIP".
 *  - Every Avaya phone fetches the SAME file, 46xxsettings.txt, over HTTP or HTTPS. Per-phone differences are
 *    made inside it with IF/GOTO branches, not with one file per phone (Avaya, "Configuring the phone using
 *    the settings file": lines begin with SET, IF, GOTO, #, ADD or GET; $MACADDR is a substitution variable).
 *  - The per-phone IDENTITY is a login at the handset: SIP user ID, authentication user ID and password are
 *    entered on the phone (emetrotel, RingCentral and Intermedia all describe the same login). So this file
 *    carries NO per-phone secret, and the screen's "first-time setup details" give the engineer the extension
 *    and its password to type in once.
 *  - Avaya ships no phone with the Open SIP load; Intermedia's guide records that the Open SIP firmware is a
 *    free download. A J179 bought for an Aura or IP Office system must be flashed before any of this applies.
 *
 * Parameter names used below were read from Avaya's own material; none is invented:
 *   SIP_CONTROLLER_LIST, SIPDOMAIN, ENFORCE_SIPS_URI, MEDIAENCRYPTION, SDPCAPNEG, TRUSTCERTS, HTTPSRVR, HTTPDIR.
 * Two settings come from an independent interoperability note (traud.de) for Asterisk specifically:
 *   SDPCAPNEG 0 (its "SDP Negotiation Capability: No") and the Opus codec turned off.
 *
 * UNPROVEN until the first physical J179 (phase 3 of the design): the exact spelling of the Opus control and
 * whether the shared file can be served behind HTTP basic auth. Both are marked in the file itself.
 */

const MODELS = {
  J179: { label: 'Avaya J179 desk phone (Open SIP)', accounts: 8, lineKeys: 8, blf: true },
  J169: { label: 'Avaya J169 desk phone (Open SIP)', accounts: 8, lineKeys: 8, blf: true },
  J139: { label: 'Avaya J139 desk phone (Open SIP)', accounts: 4, lineKeys: 4, blf: true }
};

// Avaya compares $MACADDR as upper-case hex with no separators.
const macFor = e => String(e.mac || '').toUpperCase();

function settingsFile(phones, ctx) {
  const { cfg } = ctx;
  const host = cfg.fqdn;
  const L = [];
  L.push('## GENERATED by pmc-pbx ' + new Date().toISOString() + ' - do not edit, edit the directory');
  L.push('## Avaya J100 series, Open SIP. Every Avaya phone fetches this one file; the branches below set the');
  L.push('## display name per handset. The SIP user name and password are entered at the phone itself.');
  L.push('');
  L.push('## ---- the call server ----');
  L.push('SET SIP_CONTROLLER_LIST ' + host + ':' + cfg.sipPort + ';transport=tls');
  L.push('SET SIPDOMAIN ' + host);
  L.push('SET ENFORCE_SIPS_URI 1');
  L.push('');
  L.push('## ---- media security: SRTP, and the two settings Asterisk needs ----');
  L.push('SET MEDIAENCRYPTION 1');
  L.push('SET SDPCAPNEG 0');
  L.push('');
  L.push('## ---- where this file came from, so the phone comes back for it ----');
  L.push('SET HTTPSRVR ' + host);
  L.push('SET HTTPDIR ' + (cfg.avayaDir || 'prov'));
  L.push('SET TRUSTCERTS ' + (cfg.avayaTrustCerts || ''));
  L.push('');
  L.push('## ---- time ----');
  L.push('SET SNTPSRVR ' + (cfg.ntpServer || 'pool.ntp.org'));
  L.push('SET GMTOFFSET +8:00');
  L.push('SET DSTOFFSET 0');
  L.push('');
  L.push('## ---- codecs ----');
  L.push('## The Opus codec runs fast or slow against Asterisk (independent interoperability note), so it is');
  L.push('## turned off at the phone. CONFIRM THE EXACT PARAMETER on the first handset: Avaya documents an');
  L.push('## OPUS control under "Codecs and DTMF" but its settings-file spelling was not measured.');
  L.push('## SET ENABLE_OPUS 0');
  L.push('');
  if (phones.length) {
    L.push('## ---- per handset ----');
    phones.forEach((e, i) => {
      const label = 'PH' + (i + 1);
      L.push('IF $MACADDR SEQ ' + macFor(e) + ' GOTO ' + label);
    });
    L.push('GOTO END');
    L.push('');
    phones.forEach((e, i) => {
      const label = 'PH' + (i + 1);
      L.push('# ' + label + ': ' + e.ext + ' ' + e.name + (e.dept ? ' (' + e.dept + ')' : ''));
      L.push(label);
      L.push('SET PHNNUMOFSA 1');
      L.push('SET PHONE_LABEL "' + String(e.name).replace(/"/g, '') + '"');
      L.push('GOTO END');
      L.push('');
    });
    L.push('END');
  }
  L.push('');
  return { name: '46xxsettings.txt', body: L.join('\n'), type: 'text/plain' };
}

module.exports = {
  id: 'avaya',
  vendor: 'Avaya',
  models: MODELS,
  // One file for every Avaya phone; it holds no per-phone secret, and the handset sends no password for it (no
  // per-phone file, so no provisioning password is ever made for an Avaya MAC). Served without a password, to the
  // networks in config provNetworks only (Dada, 15 Oct 2026: "yes to the network only").
  auth: 'lan',
  perPhoneFile: null,
  sharedFiles: (phones, ctx) => (phones.length ? [settingsFile(phones, ctx)] : []),
  setupNotes: e => ([
    'Firmware: the handset must carry the Open SIP load, not an Aura or IP Office one. Flash it first.',
    'File server: ' + e.url.replace(/\/$/, '') + ' serves 46xxsettings.txt; set it under Admin, default access code 27238.',
    'At the phone, log in with SIP user ID ' + e.ext + ', authentication user ID ' + e.ext + ',',
    'password: ' + (e.sipPassword || '(created at the next Apply)'),
    'This phone takes no per-phone file; everything else comes from the shared settings file.'
  ])
};
