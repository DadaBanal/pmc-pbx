'use strict';
// directory + secrets -> Asterisk includes, the phone files each vendor's driver asks for, manifest.json
const path = require('path');
const { writeFileAtomic, ensureDir, randomSecret, sha256 } = require('./fsx');
const phones = require('./phones');

function ensureSecrets(dir, secrets) {
  secrets.sip = secrets.sip || {};
  secrets.prov = secrets.prov || {};
  let created = 0;
  for (const e of dir.extensions) {
    if (!secrets.sip[e.ext]) { secrets.sip[e.ext] = randomSecret(24); created++; }
    // only a driver that fetches a per-phone file needs a provisioning password
    const d = phones.driverFor(e.model);
    if (e.mac && d && d.perPhoneFile && !secrets.prov[e.mac]) { secrets.prov[e.mac] = randomSecret(20); created++; }
  }
  return created;
}

// Which handsets each driver is responsible for in this directory.
function byDriver(dir) {
  const map = new Map();
  for (const e of dir.extensions) {
    if (!e.mac) continue;
    const d = phones.driverFor(e.model);
    if (!d || (!d.perPhoneFile && !d.sharedFiles)) continue;
    if (!map.has(d)) map.set(d, []);
    map.get(d).push(e);
  }
  return map;
}

// Every file the provisioning listener should be able to serve, and how each is guarded.
// -> [{ name, body, type, auth: 'per-mac'|'shared', mac }]
function phoneFiles(cfg, dir, secrets) {
  const out = [];
  const ctx = { cfg, dir, secrets };
  for (const [d, list] of byDriver(dir)) {
    if (d.perPhoneFile) {
      for (const e of list) {
        const f = d.perPhoneFile(e, ctx);
        if (f) out.push(Object.assign({ auth: 'per-mac', mac: e.mac, driver: d.id }, f));
      }
    }
    for (const f of (d.sharedFiles ? d.sharedFiles(list, ctx) : [])) {
      out.push(Object.assign({ auth: d.auth === 'per-mac' ? 'per-mac' : 'shared', mac: null, driver: d.id }, f));
    }
  }
  return out;
}

function generate(cfg, dir, secrets, outDir) {
  const withMac = dir.extensions.filter(e => e.mac);
  const files = phoneFiles(cfg, dir, secrets);
  ensureDir(path.join(outDir, 'asterisk'));
  ensureDir(path.join(outDir, 'phones'));
  writeFileAtomic(path.join(outDir, 'asterisk', 'pjsip_pmc.conf'), renderPjsip(dir, cfg, secrets), 0o640);
  writeFileAtomic(path.join(outDir, 'asterisk', 'extensions_pmc.conf'), renderDialplan(dir, cfg), 0o640);
  for (const f of files) writeFileAtomic(path.join(outDir, 'phones', f.name), f.body, 0o640);
  const index = {};
  for (const f of files) index[f.name] = { auth: f.auth, mac: f.mac, type: f.type || 'text/plain', driver: f.driver };
  writeFileAtomic(path.join(outDir, 'phones', 'index.json'), JSON.stringify(index, null, 2) + '\n', 0o640);
  const vendors = {};
  for (const e of withMac) { const s = phones.modelSpec(e.model); const v = s ? s.vendor : 'unknown'; vendors[v] = (vendors[v] || 0) + 1; }
  const manifest = {
    generatedAt: new Date().toISOString(),
    extensions: dir.extensions.length,
    phones: withMac.length,
    vendors,
    files: files.length,
    directoryVersion: dir.version || 0,
    directoryHash: sha256(JSON.stringify(dir.extensions) + JSON.stringify(dir.departments || [])).slice(0, 16),
    fqdn: cfg.fqdn
  };
  writeFileAtomic(path.join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return manifest;
}

function renderPjsip(dir, cfg, sec) {
  const L = [];
  L.push('; GENERATED by pmc-pbx ' + new Date().toISOString() + ' from directory version ' + (dir.version || 0) + ' - do not edit');
  L.push('');
  L.push('[transport-tls]');
  L.push('type=transport');
  L.push('protocol=tls');
  L.push('bind=0.0.0.0:' + cfg.sipPort);
  L.push('cert_file=' + cfg.certFile);
  L.push('priv_key_file=' + cfg.keyFile);
  L.push('method=tlsv1_2');
  L.push('external_media_address=' + cfg.externalIp);
  L.push('external_signaling_address=' + cfg.externalIp);
  cfg.localNets.forEach(n => L.push('local_net=' + n));
  L.push('allow_reload=no');
  L.push('');
  L.push('[pmc-endpoint](!)');
  L.push('type=endpoint');
  L.push('context=pmc-internal');
  L.push('disallow=all');
  (cfg.codecs || ['g722', 'alaw', 'ulaw']).forEach(c => L.push('allow=' + c));
  L.push('transport=transport-tls');
  L.push('media_encryption=sdes');
  L.push('media_encryption_optimistic=no');
  L.push('direct_media=no');
  L.push('rtp_symmetric=yes');
  L.push('force_rport=yes');
  L.push('rewrite_contact=yes');
  L.push('dtmf_mode=rfc4733');
  L.push('language=en');
  L.push('device_state_busy_at=1');
  L.push('');
  L.push('[pmc-auth](!)');
  L.push('type=auth');
  L.push('auth_type=userpass');
  L.push('');
  L.push('[pmc-aor](!)');
  L.push('type=aor');
  L.push('max_contacts=1');
  L.push('remove_existing=yes');
  L.push('qualify_frequency=60');
  L.push('');
  for (const e of dir.extensions) {
    const cid = '"' + e.name.replace(/"/g, '') + '" <' + e.ext + '>';
    const spec = phones.modelSpec(e.model);
    L.push('; ' + e.ext + ' ' + e.name + (e.dept ? ' (' + e.dept + ')' : '') + (spec ? ' [' + spec.vendor + ' ' + e.model + ']' : ''));
    L.push('[' + e.ext + '](pmc-endpoint)');
    L.push('auth=' + e.ext);
    L.push('aors=' + e.ext);
    L.push('callerid=' + cid);
    if (e.voicemail) L.push('mailboxes=' + e.ext + '@pmc');
    L.push('[' + e.ext + '](pmc-auth)');
    L.push('username=' + e.ext);
    L.push('password=' + sec.sip[e.ext]);
    L.push('[' + e.ext + '](pmc-aor)');
    L.push('');
  }
  return L.join('\n');
}

function renderDialplan(dir, cfg) {
  const L = [];
  L.push('; GENERATED by pmc-pbx ' + new Date().toISOString() + ' from directory version ' + (dir.version || 0) + ' - do not edit');
  L.push('');
  L.push('[pmc-internal]');
  L.push('; emergency numbers go nowhere without a trunk: say so instead of silence');
  L.push('exten => 911,1,Answer()');
  L.push(' same => n,Playback(vm-goodbye)');
  L.push(' same => n,Hangup()');
  L.push('exten => 117,1,Goto(911,1)');
  L.push('; test numbers');
  L.push('exten => 9196,1,Answer()');
  L.push(' same => n,Echo()');
  L.push(' same => n,Hangup()');
  L.push('exten => 9197,1,Answer()');
  L.push(' same => n,Playback(demo-congrats)');
  L.push(' same => n,Hangup()');
  L.push('; voicemail access');
  L.push('exten => *97,1,VoiceMailMain(${CALLERID(num)}@pmc)');
  L.push(' same => n,Hangup()');
  L.push('; hints for BLF');
  for (const e of dir.extensions) L.push('exten => ' + e.ext + ',hint,PJSIP/' + e.ext);
  L.push('; extension to extension');
  L.push('exten => _[1-8]XXX,1,NoOp(PMC call ${CALLERID(num)} -> ${EXTEN})');
  L.push(' same => n,Dial(PJSIP/${EXTEN},' + (cfg.ringSeconds || 25) + ')');
  L.push(' same => n,GotoIf($["${DIALSTATUS}" = "BUSY"]?busy)');
  L.push(' same => n,VoiceMail(${EXTEN}@pmc,u)');
  L.push(' same => n,Hangup()');
  L.push(' same => n(busy),VoiceMail(${EXTEN}@pmc,b)');
  L.push(' same => n,Hangup()');
  L.push('');
  return L.join('\n');
}

module.exports = { ensureSecrets, generate, phoneFiles, byDriver, renderPjsip, renderDialplan };
